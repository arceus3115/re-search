async function handleGatherResearch(): Promise<void> {
    const nameInput = document.getElementById('pi-name') as HTMLInputElement;
    const orcidInput = document.getElementById('pi-orcid') as HTMLInputElement;
    const openalexInput = document.getElementById('pi-openalex-id') as HTMLInputElement;
    const institutionInput = document.getElementById('pi-institution') as HTMLInputElement;
    const gatherBtn = document.getElementById('gather-research-btn') as HTMLButtonElement;
    const summarySection = document.getElementById('pi-summary-section');
    const papersSection = document.getElementById('papers-section');

    if (!nameInput || !gatherBtn) return;

    const piName = nameInput.value.trim();
    if (!piName) {
        alert('Please enter a PI name');
        return;
    }

    // Show loading state
    gatherBtn.disabled = true;
    gatherBtn.textContent = 'Gathering Research...';

    try {
        const summaryFocusSelect = document.getElementById('summary-focus-select') as HTMLSelectElement;
        const summaryFocus = summaryFocusSelect?.value || undefined;

        const requestBody: any = {
            pi_name: piName || undefined,
            orcid: orcidInput?.value.trim() || undefined,
            openalex_id: openalexInput?.value.trim() || undefined,
            institution: institutionInput?.value.trim() || undefined,
            summary_focus: summaryFocus,
        };

        // Remove undefined values
        Object.keys(requestBody).forEach(key => {
            if (requestBody[key] === undefined) {
                delete requestBody[key];
            }
        });

        const response = await fetch('/api/v1/pi-research/gather', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(requestBody),
        });

        if (!response.ok) {
            const error = await response.json();
            throw new Error(error.detail || 'Failed to gather PI research');
        }

        const data: any = await response.json();

        // Check if multiple matches were returned
        if (data.multiple_matches && data.candidates) {
            // Show candidate selection UI
            if (summarySection) {
                const summaryContent = document.getElementById('pi-summary-content');
                if (summaryContent) {
                    summaryContent.innerHTML = `
                        <div class="pi-info">
                            <h4>Multiple Researchers Found</h4>
                            <p>Please select the correct researcher:</p>
                            <div id="pi-candidates-list" style="margin-top: 1rem;">
                                ${data.candidates.map((candidate: any, idx: number) => {
                                    // Get institutions - try last_known_institutions first, then affiliated_institutions, then institution
                                    let institutions: string[] = [];
                                    if (candidate.last_known_institutions && Array.isArray(candidate.last_known_institutions)) {
                                        institutions = candidate.last_known_institutions.map((inst: any) =>
                                            typeof inst === 'string' ? inst : (inst.display_name || inst.name || '')
                                        ).filter((inst: string) => inst);
                                    } else if (candidate.affiliated_institutions && Array.isArray(candidate.affiliated_institutions)) {
                                        institutions = candidate.affiliated_institutions;
                                    } else if (candidate.institution) {
                                        institutions = [candidate.institution];
                                    }
                                    return `
                                    <div class="candidate-select-card" style="background-color: white; border: 2px solid #dee2e6; border-radius: 8px; padding: 1rem; margin-bottom: 0.75rem; cursor: pointer; transition: border-color 0.2s;"
                                         data-openalex-id="${candidate.openalex_id}">
                                        <div>
                                            <h5 style="margin: 0 0 0.5rem 0;">${candidate.name}</h5>
                                            ${institutions.length > 0 ? `<p style="margin: 0 0 0.5rem 0; color: #666; font-size: 0.9em;"><strong>Institutions:</strong> ${institutions.join(', ')}</p>` : ''}
                                            ${candidate.subjects && candidate.subjects.length > 0 ? `<p style="margin: 0 0 0.5rem 0; color: #666; font-size: 0.9em;"><strong>Subjects:</strong> ${candidate.subjects.join(', ')}</p>` : ''}
                                            <div style="font-size: 0.9em; color: #666;">
                                                <strong>h-index:</strong> ${candidate.h_index || 0}
                                            </div>
                                        </div>
                                    </div>
                                `;
                                }).join('')}
                            </div>
                        </div>
                    `;
                    summarySection.style.display = 'block';

                    // Add click handlers for candidate selection
                    document.querySelectorAll('.candidate-select-card').forEach(card => {
                        card.addEventListener('click', async () => {
                            const openalexId = (card as HTMLElement).dataset.openalexId;
                            if (openalexId) {
                                // Gather research for selected candidate
                                gatherBtn.disabled = true;
                                gatherBtn.textContent = 'Gathering Research...';

                                try {
                                    const selectResponse = await fetch('/api/v1/pi-research/gather', {
                                        method: 'POST',
                                        headers: { 'Content-Type': 'application/json' },
                                        body: JSON.stringify({ openalex_id: openalexId }),
                                    });

                                    if (!selectResponse.ok) {
                                        const error = await selectResponse.json();
                                        throw new Error(error.detail || 'Failed to gather PI research');
                                    }

                                    const selectedData: PIResearchData = await selectResponse.json();
                                    currentPIResearch = selectedData;

                                    // Display selected PI summary
                                    displayPIResearch(selectedData);

                                } catch (error: any) {
                                    console.error('Error gathering research:', error);
                                    alert(`Error: ${error.message}`);
                                } finally {
                                    gatherBtn.disabled = false;
                                    gatherBtn.textContent = 'Gather Research';
                                }
                            }
                        });

                        // Add hover effect
                        card.addEventListener('mouseenter', () => {
                            (card as HTMLElement).style.borderColor = '#007bff';
                        });
                        card.addEventListener('mouseleave', () => {
                            (card as HTMLElement).style.borderColor = '#dee2e6';
                        });
                    });
                }
            }
            return;
        }

        // Single match - proceed normally
        const piData: PIResearchData = data;
        currentPIResearch = piData;

        // Display PI summary
        displayPIResearch(piData);

        // Enable generate button if we have a profile
        const generateBtn = document.getElementById('generate-draft-btn') as HTMLButtonElement;
        if (generateBtn && currentProfileId) {
            generateBtn.disabled = false;
        } else if (generateBtn) {
            generateBtn.disabled = true;
            generateBtn.title = 'Please create a profile first';
        }

    } catch (error: any) {
        console.error('Error gathering research:', error);
        alert(`Error: ${error.message}`);
    } finally {
        gatherBtn.disabled = false;
        gatherBtn.textContent = 'Gather Research';
    }
}

async function handleGenerateDraft(): Promise<void> {
    if (!currentProfileId) {
        alert('Please create a profile first');
        return;
    }

    if (!currentPIResearch) {
        alert('Please gather PI research first');
        return;
    }

    const formatEmailBtn = document.getElementById('format-email');
    const isEmail = formatEmailBtn?.classList.contains('active');
    const formatType = isEmail ? 'email' : 'statement';

    const generateBtn = document.getElementById('generate-draft-btn') as HTMLButtonElement;
    const $ = (window as any).jQuery;
    const editor = document.getElementById('draft-editor');

    if (!generateBtn || !editor) return;

    // Save current editor content as a version before generating (if not empty)
    const currentContent = $(editor).hasClass('summernote-initialized')
        ? $(editor).summernote('code') || ''
        : (editor as HTMLTextAreaElement).value || '';

    if (currentContent.trim()) {
        saveCurrentVersion(false);
    }

    // Show loading
    generateBtn.disabled = true;
    generateBtn.textContent = 'Generating...';

    try {
        const requestBody: any = {
            profile_id: currentProfileId,
            pi_research_data: currentPIResearch,
            format_type: formatType,
        };

        // Get user draft from editor
        const userDraft = currentContent.trim();
        if (formatType === 'email') {
            const wordCount = parseInt((document.getElementById('email-word-count-target') as HTMLInputElement)?.value || '300');
            if (userDraft) {
                requestBody.user_draft = userDraft;
            }
            requestBody.word_count_target = wordCount;
        } else {
            const wordCount = parseInt((document.getElementById('statement-word-count-target') as HTMLInputElement)?.value || '375');
            if (userDraft) {
                requestBody.user_draft = userDraft;
            }
            requestBody.word_count_target = wordCount;
        }

        const response = await fetch('/api/v1/draft/generate', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(requestBody),
        });

        if (!response.ok) {
            const error = await response.json();
            throw new Error(error.detail || 'Failed to generate draft');
        }

        const result = await response.json();

        // Repopulate editor with generated content
        if (formatType === 'email') {
            const subjectInput = document.getElementById('email-subject') as HTMLInputElement;
            if (subjectInput) {
                subjectInput.value = result.subject || '';
                emailContent.subject = result.subject || '';
            }

            // Set body in editor
            if ($(editor).hasClass('summernote-initialized')) {
                $(editor).summernote('code', result.body || '');
            } else {
                (editor as HTMLTextAreaElement).value = result.body || '';
            }
            emailContent.body = result.body || '';
        } else {
            // Set statement in editor
            if ($(editor).hasClass('summernote-initialized')) {
                $(editor).summernote('code', result.statement || '');
            } else {
                (editor as HTMLTextAreaElement).value = result.statement || '';
            }
            statementContent = result.statement || '';
        }

        // Save generated content as a new version
        saveCurrentVersion(true);
        updateWordCount();

    } catch (error: any) {
        console.error('Error generating draft:', error);
        alert(`Error: ${error.message}`);
    } finally {
        generateBtn.disabled = false;
        generateBtn.textContent = 'Generate Draft';
    }
}

