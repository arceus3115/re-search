function switchFormat(format: 'email' | 'statement'): void {
    // Save current content before switching
    const $ = (window as any).jQuery;
    const editor = document.getElementById('draft-editor');
    const formatEmailBtn = document.getElementById('format-email');
    const currentFormat = formatEmailBtn?.classList.contains('active') ? 'email' : 'statement';

    if (currentFormat !== format) {
        // Save current format's content
        if (currentFormat === 'email') {
            if (editor && $(editor).hasClass('summernote-initialized')) {
                emailContent.body = $(editor).summernote('code') || '';
            } else if (editor) {
                emailContent.body = (editor as HTMLTextAreaElement).value || '';
            }
            const subjectInput = document.getElementById('email-subject') as HTMLInputElement;
            if (subjectInput) {
                emailContent.subject = subjectInput.value || '';
            }
        } else {
            if (editor && $(editor).hasClass('summernote-initialized')) {
                statementContent = $(editor).summernote('code') || '';
            } else if (editor) {
                statementContent = (editor as HTMLTextAreaElement).value || '';
            }
        }
    }

    const emailBtn = document.getElementById('format-email');
    const statementBtn = document.getElementById('format-statement');
    const emailOptions = document.getElementById('email-options');
    const statementOptions = document.getElementById('statement-options');
    const editorEl = document.getElementById('draft-editor');

    if (format === 'email') {
        emailBtn?.classList.add('active');
        statementBtn?.classList.remove('active');
        emailOptions?.setAttribute('style', 'display: block;');
        statementOptions?.setAttribute('style', 'display: none;');

        // Load email content
        if (editorEl && $(editorEl).hasClass('summernote-initialized')) {
            $(editorEl).summernote('code', emailContent.body);
        } else if (editorEl) {
            (editorEl as HTMLTextAreaElement).value = emailContent.body;
        }
        const subjectInput = document.getElementById('email-subject') as HTMLInputElement;
        if (subjectInput) {
            subjectInput.value = emailContent.subject;
        }
    } else {
        emailBtn?.classList.remove('active');
        statementBtn?.classList.add('active');
        emailOptions?.setAttribute('style', 'display: none;');
        statementOptions?.setAttribute('style', 'display: block;');

        // Load statement content
        if (editorEl && $(editorEl).hasClass('summernote-initialized')) {
            $(editorEl).summernote('code', statementContent);
        } else if (editorEl) {
            (editorEl as HTMLTextAreaElement).value = statementContent;
        }
    }

    updateWordCount();
}

